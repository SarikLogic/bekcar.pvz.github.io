function normalizeText(text) {
    return text.trim().replace(/\s+/g, ' ');
}

document.addEventListener('DOMContentLoaded', () => {
    const textNodes = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement && (node.parentElement.tagName === 'SCRIPT' || node.parentElement.tagName === 'STYLE')) continue;
        
        const originalSpacing = node.nodeValue;
        const normalized = normalizeText(originalSpacing);
        if (normalized && dict[normalized]) {
            textNodes.push({
                node: node,
                normalized: normalized,
                originalSpacing: originalSpacing
            });
        }
    }

    const placeholderElements = [];
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
        const originalText = normalizeText(el.getAttribute('placeholder'));
        if (originalText && dict[originalText]) {
            placeholderElements.push({
                el: el,
                originalText: originalText
            });
        }
    });

    window.changeLang = function(lang) {
        localStorage.setItem('bekcar_lang', lang);
        
        const currentLangEl = document.getElementById('currentLang');
        if (currentLangEl) currentLangEl.textContent = lang.toUpperCase();

        document.documentElement.lang = lang;

        textNodes.forEach(item => {
            if (lang === 'uz') {
                item.node.nodeValue = item.originalSpacing;
            } else {
                const translated = dict[item.normalized][lang];
                if (translated) {
                    item.node.nodeValue = item.originalSpacing.replace(item.normalized, translated);
                }
            }
        });

        placeholderElements.forEach(item => {
            if (lang === 'uz') {
                item.el.setAttribute('placeholder', item.originalText);
            } else {
                const translated = dict[item.originalText][lang];
                if (translated) {
                    item.el.setAttribute('placeholder', translated);
                }
            }
        });
    };

    const savedLang = localStorage.getItem('bekcar_lang') || 'en';
    changeLang(savedLang);
});
